const DICTS: Record<Lang, Dict> = { en, uz, ru };

export const LANGUAGES: { id: LangPref; label: string }[] = [
  { id: 'system', label: 'Auto' },
  { id: 'en', label: 'English' },
  { id: 'uz', label: 'O‘zbekcha' },
  { id: 'ru', label: 'Русский' },
];

function detectSystem(): Lang {
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const base = l.toLowerCase().slice(0, 2);
    if (base === 'uz' || base === 'ru' || base === 'en') return base;
  }
  return 'en';
}

function initial(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as LangPref | null;
    if (saved === 'en' || saved === 'uz' || saved === 'ru') return saved;
  } catch {
    // ignore
  }
  return detectSystem();
}

let current: Lang = initial();

/** Apply a language preference (called from VaultContext on pref change). */
export function setLanguage(pref: LangPref | undefined): void {
  const next = !pref || pref === 'system' ? detectSystem() : pref;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, pref ?? 'system');
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next;
}

export const getLanguage = (): Lang => current;

/** BCP-47 locale for dates/numbers. */
export const getLocale = (): string =>
  current === 'uz' ? 'uz-Latn-UZ' : current === 'ru' ? 'ru-RU' : 'en-US';

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Dictionary coverage check used by tests. */
export function missingKeys(lang: Lang): string[] {
  return Object.keys(en).filter((k) => !(k in DICTS[lang]));
}
